class InvalidAsset(ValueError):
    pass


def check(condition: bool, message: str) -> None:
    if not condition:
        raise InvalidAsset(message)


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def chunks(data: bytes):
    offset = 12
    while offset < len(data):
        check(offset + 8 <= len(data), "truncated GLB chunk header")
        size, kind = struct.unpack_from("<II", data, offset)
        offset += 8
        check(offset + size <= len(data), "truncated GLB chunk")
        yield kind, data[offset:offset + size]
        offset += size
    check(offset == len(data), "GLB chunk alignment/trailing bytes error")


def parse_glb(path: Path) -> tuple[dict, bytes]:
    data = path.read_bytes()
    check(len(data) >= 20, f"{path.name}: too small to be a GLB")
    magic, version, length = struct.unpack_from("<4sII", data, 0)
    check(magic == b"glTF" and version == 2 and length == len(data), f"{path.name}: invalid GLB header")
    parsed = list(chunks(data))
    check(parsed[0][0] == 0x4E4F534A, f"{path.name}: JSON chunk must be first")
    js = json.loads(parsed[0][1].rstrip(b" \0\t\r\n").decode("utf-8"))
    binary = b""
    for kind, payload in parsed[1:]:
        if kind == 0x004E4942:
            check(not binary, f"{path.name}: duplicate BIN chunk")
            binary = payload
    check(js.get("asset", {}).get("version") == "2.0", f"{path.name}: not glTF 2.0")
    check(len(js.get("buffers", [])) == 1 and "uri" not in js["buffers"][0], f"{path.name}: missing embedded GLB buffer")
    check(js["buffers"][0]["byteLength"] <= len(binary) <= js["buffers"][0]["byteLength"] + 3,
          f"{path.name}: invalid GLB buffer length")
    return js, binary


COMPONENT_SIZES = {5120: 1, 5121: 1, 5122: 2, 5123: 2, 5125: 4, 5126: 4}
TYPE_WIDTHS = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4, "MAT2": 4, "MAT3": 9, "MAT4": 16}


def validate_binary_ranges(path: Path, js: dict, binary: bytes) -> None:
    views = js.get("bufferViews", [])
    for i, view in enumerate(views):
        check(view.get("buffer", 0) == 0, f"{path.name}: bufferView {i} references a non-GLB buffer")
        start = view.get("byteOffset", 0)
        length = view.get("byteLength", -1)
        check(start >= 0 and length >= 0 and start + length <= len(binary), f"{path.name}: bufferView {i} outside BIN chunk")
    accessors = js.get("accessors", [])
    for i, accessor in enumerate(accessors):
        check("sparse" not in accessor, f"{path.name}: unexpected sparse accessor {i}")
        check(0 <= accessor.get("bufferView", -1) < len(views), f"{path.name}: accessor {i} has invalid bufferView")
        check(accessor.get("componentType") in COMPONENT_SIZES, f"{path.name}: accessor {i} has invalid component type")
        check(accessor.get("type") in TYPE_WIDTHS and accessor.get("count", 0) > 0, f"{path.name}: accessor {i} has invalid shape")
        view = views[accessor["bufferView"]]
        width = TYPE_WIDTHS[accessor["type"]] * COMPONENT_SIZES[accessor["componentType"]]
        stride = view.get("byteStride", width)
        start = view.get("byteOffset", 0) + accessor.get("byteOffset", 0)
        end = start + (accessor["count"] - 1) * stride + width
        check(stride >= width and start >= 0 and end <= view.get("byteOffset", 0) + view["byteLength"],
              f"{path.name}: accessor {i} exceeds its bufferView")


def quat_rotate(q: list[float], v: tuple[float, float, float]) -> tuple[float, float, float]:
    x, y, z, w = q
    vx, vy, vz = v
    # q * [v,0] * conjugate(q), expanded without temporary allocations.
    tx, ty, tz = 2 * (y * vz - z * vy), 2 * (z * vx - x * vz), 2 * (x * vy - y * vx)
    return (vx + w * tx + y * tz - z * ty,
            vy + w * ty + z * tx - x * tz,
            vz + w * tz + x * ty - y * tx)


def validate_mark_i_running_gear(js: dict) -> dict:
    """Cross-check wheel radii, belt contact, and sponson yaw against the GLB and Java pose code."""
    wwi_dir = str(ROOT / "tools/wwi")
    if wwi_dir not in sys.path:
        sys.path.insert(0, wwi_dir)
    from build_mark_i import (END_WHEEL_RADIUS, ROAD_WHEEL_RADIUS, RETURN_ROLLER_RADIUS,
                              ROAD_WHEEL_CENTER_Y, RETURN_ROLLER_CENTER_Y, TRACK_HALF_THICKNESS,
                              TRACK_LINKS, TRACK_PATH, loop_length)

    meshes = {mesh.get("name"): mesh for mesh in js.get("meshes", [])}
    accessors = js.get("accessors", [])

    def radial_radius(mesh_name: str) -> float:
        check(mesh_name in meshes, f"Mark I GLB: missing running-gear mesh {mesh_name}")
        radius = 0.0
        for primitive in meshes[mesh_name].get("primitives", []):
            bounds = accessors[primitive["attributes"]["POSITION"]]
            check(bounds.get("type") == "VEC3" and len(bounds.get("min", [])) == 3 and len(bounds.get("max", [])) == 3,
                  f"Mark I GLB: invalid vertex bounds for {mesh_name}")
            radius = max(radius, *(abs(float(bounds[key][axis])) for key in ("min", "max") for axis in (1, 2)))
        return radius

    radii = {"road_wheel": radial_radius("road_wheel"),
             "end_wheel": radial_radius("end_wheel"),
             "return_roller": radial_radius("return_roller")}
    expected_radii = {"road_wheel": ROAD_WHEEL_RADIUS, "end_wheel": END_WHEEL_RADIUS,
                      "return_roller": RETURN_ROLLER_RADIUS}
    for name, expected in expected_radii.items():
        check(abs(radii[name] - expected) < 1e-6,
              f"Mark I GLB: {name} radius {radii[name]:.6f} m does not match {expected:.3f} m")

    # Compare the GLB's actual wheel meshes with the Cfg values consumed by GunVehicle's animation.
    gear_source = (ROOT / "mods/aiarsenal/src/main/java/ru/aiforge/realwar/vehicle/GunVehicle.java").read_text(encoding="utf-8")
    gear_match = re.search(
        r"case MARK_I\s*->\s*new Cfg\([^;]*?\n\s*"
        r"([-+]?\d+(?:\.\d+)?)f,\s*([-+]?\d+(?:\.\d+)?)f,\s*([-+]?\d+(?:\.\d+)?)f,\s*"
        r"([-+]?\d+(?:\.\d+)?)f,\s*([-+]?\d+(?:\.\d+)?)f,\s*(\d+),\s*(\d+),\s*([-+]?\d+(?:\.\d+)?)f",
        gear_source,
    )
    check(gear_match is not None, "GunVehicle.java: cannot read Mark I running-gear configuration")
    track_half, road, sprocket, idler, roller = map(float, gear_match.groups()[:5])
    road_count, roller_count = map(int, gear_match.groups()[5:7])
    pitch = float(gear_match.group(8))
    check(abs(road - radii["road_wheel"]) < 1e-6 and abs(sprocket - radii["end_wheel"]) < 1e-6
          and abs(idler - radii["end_wheel"]) < 1e-6 and abs(roller - radii["return_roller"]) < 1e-6,
          "GunVehicle.java Mark I radii do not match the generated GLB meshes")
    nodes = {node.get("name"): node for node in js.get("nodes", []) if node.get("name")}
    check(road_count == 6 and roller_count == 3, "GunVehicle.java Mark I wheel counts differ from the model")
    for side in ("L", "R"):
        check(all(f"rw_{side}_{i}" in nodes for i in range(road_count)), f"Mark I GLB: missing {side} road wheels")
        check(all(f"rr_{side}_{i}" in nodes for i in range(roller_count)), f"Mark I GLB: missing {side} return rollers")
        road_pos = nodes[f"rw_{side}_0"].get("translation", [0, 0, 0])
        roller_pos = nodes[f"rr_{side}_0"].get("translation", [0, 0, 0])
        road_x = abs(road_pos[0])
        link_x = nodes.get(f"MarkI_link_{side}_00", {}).get("translation", [0, 0, 0])[0]
        check(track_half > road_x + 0.1 and abs(abs(link_x) - track_half) < 1e-6,
              "road-wheel centers and GLB link path disagree with the track half-width")
        check(abs(road_pos[1] - ROAD_WHEEL_CENTER_Y) < 1e-6
              and abs(roller_pos[1] - RETURN_ROLLER_CENTER_Y) < 1e-6,
              "road wheels/return rollers are not tangent to the inner face of their track runs")

    # The linked shoe loop's measured length is the source of the pitch used to spin the wheels and belt.
    expected_pitch = loop_length() / TRACK_LINKS
    check(TRACK_LINKS == 56 and abs(pitch - expected_pitch) < 1e-7,
          f"Mark I GLB track pitch mismatch: cfg={pitch:.9f}, generated={expected_pitch:.9f}")

    # Both mounts start facing outward, but applyPose counter-rotates them to exactly the common projectile azimuth.
    expected_bind = {"launcher_yaw": (-1.0, 0.0, 0.0), "launcher_yaw_left": (1.0, 0.0, 0.0)}
    bind_yaw = {}
    for name, expected in expected_bind.items():
        check(name in nodes, f"Mark I GLB: missing sponson pivot {name}")
        rotation = nodes[name].get("rotation", [0.0, 0.0, 0.0, 1.0])
        direction = quat_rotate(rotation, (0.0, 0.0, 1.0))
        check(max(abs(direction[i] - expected[i]) for i in range(3)) < 1e-6,
              f"Mark I GLB: {name} does not start facing outward")
        bind_yaw[name] = 2.0 * math.atan2(rotation[1], rotation[3])
    launcher_source = (ROOT / "mods/aiarsenal/src/main/java/ru/aiforge/realwar/vehicle/LauncherVehicle.java").read_text(encoding="utf-8")
    check(re.search(r'pose\.rotate\("launcher_yaw",\s*\(float\)Math\.toRadians\(azR\s*\+\s*90\.0f\)', launcher_source)
          and re.search(r'pose\.rotate\("launcher_yaw_left",\s*\(float\)Math\.toRadians\(azL\s*-\s*90\.0f\)', launcher_source)
          and re.search(r'float azR = this\.kind\.sponsonAz\(0, az\), azL = this\.kind\.sponsonAz\(1, az\)', launcher_source),
          "LauncherVehicle.applyPose Mark I yaw offsets differ from the generated bind rotations "
          "(must counter-rotate the clamped sponson azimuths azR/azL by the bind +-90 deg)")
    for azimuth in (-180.0, -90.0, 0.0, 45.0, 135.0, 180.0):
        az = math.radians(azimuth)
        expected = (math.sin(az), 0.0, math.cos(az))
        for name, offset in (("launcher_yaw", 90.0), ("launcher_yaw_left", -90.0)):
            delta = math.radians(azimuth + offset)
            final_yaw = bind_yaw[name] + delta
            actual = (math.sin(final_yaw), 0.0, math.cos(final_yaw))
            check(max(abs(actual[i] - expected[i]) for i in range(3)) < 1e-6,
                  f"Mark I {name} aim diverges at azimuth {azimuth:g} degrees")
    return {"radii": radii, "pitch": pitch, "road_count": road_count, "roller_count": roller_count,
            "road_center_y": ROAD_WHEEL_CENTER_Y, "roller_center_y": RETURN_ROLLER_CENTER_Y}


def apply_trs(node: dict, p: tuple[float, float, float]) -> tuple[float, float, float]:
    s = node.get("scale", (1.0, 1.0, 1.0))
    v = (p[0] * s[0], p[1] * s[1], p[2] * s[2])
    v = quat_rotate(node.get("rotation", (0.0, 0.0, 0.0, 1.0)), v)
    t = node.get("translation", (0.0, 0.0, 0.0))
    return (v[0] + t[0], v[1] + t[1], v[2] + t[2])


def world_bounds(js: dict) -> tuple[tuple[float, float, float], tuple[float, float, float]]:
    nodes = js.get("nodes", [])
    meshes = js.get("meshes", [])
    accessors = js.get("accessors", [])
    scene_index = js.get("scene", 0)
    check(0 <= scene_index < len(js.get("scenes", [])), "invalid default scene index")
    low = [math.inf, math.inf, math.inf]
    high = [-math.inf, -math.inf, -math.inf]

    def visit(index: int, parent):
        check(0 <= index < len(nodes), f"invalid node index {index}")
        node = nodes[index]
        def transform(p):
            return parent(apply_trs(node, p))
        if "mesh" in node:
            check(0 <= node["mesh"] < len(meshes), f"node {node.get('name')} references a missing mesh")
            for primitive in meshes[node["mesh"]].get("primitives", []):
                pos = accessors[primitive["attributes"]["POSITION"]]
                mn, mx = pos["min"], pos["max"]
                for mask in range(8):
                    p = tuple(mx[a] if (mask >> a) & 1 else mn[a] for a in range(3))
                    q = transform(p)
                    for axis in range(3):
                        low[axis] = min(low[axis], q[axis])
                        high[axis] = max(high[axis], q[axis])
        for child in node.get("children", []):
            visit(child, transform)

    identity = lambda p: p
    for root_node in js["scenes"][scene_index].get("nodes", []):
        visit(root_node, identity)
    check(all(math.isfinite(x) for x in low + high), "model has no reachable mesh geometry")
    return tuple(low), tuple(high)


def png_size_and_crc(data: bytes, label: str) -> tuple[int, int]:
    check(data.startswith(b"\x89PNG\r\n\x1a\n"), f"{label}: bad PNG signature")
    pos = 8
    width = height = 0
    bit_depth = color_type = -1
    idat = bytearray()
    saw_iend = False
    while pos < len(data):
        check(pos + 12 <= len(data), f"{label}: truncated PNG chunk")
        size = struct.unpack_from(">I", data, pos)[0]
        kind = data[pos + 4:pos + 8]
        end = pos + 12 + size
        check(end <= len(data), f"{label}: truncated PNG payload")
        payload = data[pos + 8:pos + 8 + size]
        stored_crc = struct.unpack_from(">I", data, pos + 8 + size)[0]
        check((zlib.crc32(kind + payload) & 0xFFFFFFFF) == stored_crc, f"{label}: PNG CRC mismatch in {kind!r}")
        if kind == b"IHDR":
            check(size == 13, f"{label}: invalid PNG IHDR")
            width, height = struct.unpack_from(">II", payload, 0)
            bit_depth, color_type = payload[8], payload[9]
            check(payload[10:13] == b"\0\0\0", f"{label}: unsupported PNG compression/filter/interlace")
        elif kind == b"IDAT":
            idat.extend(payload)
        if kind == b"IEND":
            check(size == 0 and end == len(data), f"{label}: invalid PNG end")
            saw_iend = True
            break
        pos = end
    check(width > 0 and height > 0 and saw_iend, f"{label}: incomplete PNG")
    check(bit_depth == 8 and color_type == 6 and idat, f"{label}: expected non-empty 8-bit RGBA PNG")
    raw = zlib.decompress(idat)
    check(len(raw) == height * (1 + width * 4), f"{label}: decoded PNG byte count mismatch")
    return width, height


def validate_glb(path: Path, expected_animations: set[str], expected_nodes: set[str]) -> dict:
    js, binary = parse_glb(path)
    validate_binary_ranges(path, js, binary)
    nodes = js.get("nodes", [])
    names = [node.get("name") for node in nodes if node.get("name")]
    check(len(names) == len(set(names)), f"{path.name}: node names must be unique")
    check(expected_nodes <= set(names), f"{path.name}: missing nodes {sorted(expected_nodes - set(names))}")
    for node in nodes:
        for child in node.get("children", []):
            check(0 <= child < len(nodes), f"{path.name}: invalid child node in {node.get('name')}")
        if "mesh" in node:
            check(0 <= node["mesh"] < len(js.get("meshes", [])), f"{path.name}: invalid mesh index")
    triangles = 0
    for mi, mesh in enumerate(js.get("meshes", [])):
        for primitive in mesh.get("primitives", []):
            check(primitive.get("mode", 4) == 4, f"{path.name}: non-triangle primitive")
            check(0 <= primitive.get("material", -1) < len(js.get("materials", [])), f"{path.name}: invalid material")
            attrs = primitive.get("attributes", {})
            check("POSITION" in attrs and "NORMAL" in attrs and "TEXCOORD_0" in attrs,
                  f"{path.name}: incomplete vertex attributes in mesh {mi}")
            pos = js["accessors"][attrs["POSITION"]]
            nor = js["accessors"][attrs["NORMAL"]]
            uv = js["accessors"][attrs["TEXCOORD_0"]]
            check(pos["type"] == "VEC3" and pos["componentType"] == 5126
                  and len(pos.get("min", [])) == 3 and len(pos.get("max", [])) == 3,
                  f"{path.name}: POSITION accessor is missing finite float bounds in mesh {mi}")
            check(all(math.isfinite(float(x)) for x in pos["min"] + pos["max"]), f"{path.name}: non-finite POSITION bounds")
            check(nor["count"] == pos["count"] and uv["count"] == pos["count"],
                  f"{path.name}: vertex attribute counts disagree in mesh {mi}")
            idx = js["accessors"][primitive["indices"]]
            check(idx["type"] == "SCALAR" and idx["count"] % 3 == 0, f"{path.name}: index list is not triangles")
            triangles += idx["count"] // 3
            # Verify triangle winding vs vertex normals and absence of opposite-winding z-fighting faces
            views = js["bufferViews"]
            pv = views[pos["bufferView"]]
            nv = views[nor["bufferView"]]
            iv = views[idx["bufferView"]]
            p_off = pv.get("byteOffset", 0) + pos.get("byteOffset", 0)
            n_off = nv.get("byteOffset", 0) + nor.get("byteOffset", 0)
            i_off = iv.get("byteOffset", 0) + idx.get("byteOffset", 0)
            p_str = pv.get("byteStride", 12)
            n_str = nv.get("byteStride", 12)
            i_fmt, i_sz = {5121: ("B", 1), 5123: ("H", 2), 5125: ("I", 4)}[idx["componentType"]]
            i_str = iv.get("byteStride", i_sz)
            pts = [struct.unpack_from("<fff", binary, p_off + k * p_str) for k in range(pos["count"])]
            nrms = [struct.unpack_from("<fff", binary, n_off + k * n_str) for k in range(nor["count"])]
            inds = [struct.unpack_from("<" + i_fmt, binary, i_off + k * i_str)[0] for k in range(idx["count"])]
            seen_tris: dict[tuple, tuple[float, float, float]] = {}
            for k in range(0, len(inds) - 2, 3):
                a, b, c = pts[inds[k]], pts[inds[k + 1]], pts[inds[k + 2]]
                ux, uy, uz = b[0] - a[0], b[1] - a[1], b[2] - a[2]
                vx, vy, vz = c[0] - a[0], c[1] - a[1], c[2] - a[2]
                nx, ny, nz = uy * vz - uz * vy, uz * vx - ux * vz, ux *vy - uy * vx
                ln = math.sqrt(nx * nx + ny * ny + nz * nz)
                check(ln >= 1e-10, f"{path.name}: degenerate triangle in mesh {mesh.get('name', mi)}")
                nx, ny, nz = nx / ln, ny / ln, nz / ln
                vn = nrms[inds[k]]
                check(nx * vn[0] + ny * vn[1] + nz * vn[2] >= 0.25,
                      f"{path.name}: inverted/mismatched normal in mesh {mesh.get('name', mi)}")
                key = tuple(sorted(tuple(round(v, 5) for v in p) for p in (a, b, c)))
                if key in seen_tris:
                    pn = seen_tris[key]
                    check(nx * pn[0] + ny * pn[1] + nz * pn[2] > -0.5,
                          f"{path.name}: opposite-winding z-fighting triangles in mesh {mesh.get('name', mi)}")
                else:
                    seen_tris[key] = (nx, ny, nz)
    check(triangles > 0, f"{path.name}: no triangle geometry")
    material_refs = [m.get("pbrMetallicRoughness", {}).get("baseColorTexture", {}).get("index") for m in js.get("materials", [])]
    check(material_refs and all(isinstance(i, int) and 0 <= i < len(js.get("textures", [])) for i in material_refs),
          f"{path.name}: materials are missing a real texture reference")
    for image in js.get("images", []):
        check("uri" not in image and "bufferView" in image, f"{path.name}: texture must be embedded")
        view = js["bufferViews"][image["bufferView"]]
        offset = view.get("byteOffset", 0)
        width, height = png_size_and_crc(binary[offset:offset + view["byteLength"]], f"{path.name} embedded texture")
        check(width >= 16 and height >= 16, f"{path.name}: unexpectedly tiny texture")
    animations = {a.get("name"): a for a in js.get("animations", [])}
    check(expected_animations <= set(animations), f"{path.name}: missing animations {sorted(expected_animations - set(animations))}")
    for name, animation in animations.items():
        check(animation.get("channels") and animation.get("samplers"), f"{path.name}: empty animation {name}")
        for channel in animation["channels"]:
            check(0 <= channel.get("target", {}).get("node", -1) < len(nodes), f"{path.name}: invalid animation target in {name}")
            check(channel.get("target", {}).get("path") in {"translation", "rotation", "scale", "weights"},
                  f"{path.name}: invalid animation path in {name}")
            sampler = animation["samplers"][channel["sampler"]]
            tin = js["accessors"][sampler["input"]]
            tout = js["accessors"][sampler["output"]]
            check(tin["componentType"] == 5126 and tin["type"] == "SCALAR" and tin["count"] >= 2,
                  f"{path.name}: invalid animation time stream in {name}")
            check(tout["count"] == tin["count"], f"{path.name}: animation key count mismatch in {name}")
    lo, hi = world_bounds(js)
    return {"triangles": triangles, "nodes": len(nodes), "meshes": len(js.get("meshes", [])),
            "animations": len(animations), "bounds": (lo, hi), "bytes": path.stat().st_size}


def validate_deck(path: Path) -> dict:
    data = path.read_bytes()
    check(len(data) >= 16, f"{path.name}: deck file too short")
    version, res, groups = struct.unpack_from(">ifi", data, 0)
    check(version == 2 and math.isfinite(res) and 0.0 < res <= 1.0 and 0 <= groups <= 32,
          f"{path.name}: invalid deck header")
    offset = 12
    pivots = {}
    for _ in range(groups):
        group, x, z = struct.unpack_from(">iff", data, offset)
        offset += 12
        check(group >= 0 and math.isfinite(x) and math.isfinite(z), f"{path.name}: invalid deck pivot")
        check(group not in pivots, f"{path.name}: duplicate deck group {group}")
        pivots[group] = (x, z)
    count, = struct.unpack_from(">i", data, offset)
    offset += 4
    check(0 < count < 10000, f"{path.name}: unreasonable collision-box count {count}")
    boxes = []
    for _ in range(count):
        row = struct.unpack_from(">bffffff", data, offset)
        offset += 25
        group, *coords = row
        check(all(math.isfinite(x) for x in coords), f"{path.name}: non-finite collision box")
        check(coords[0] < coords[3] and coords[1] < coords[4] and coords[2] < coords[5], f"{path.name}: inverted collision box")
        check(group >= 0 and (group == 0 or group in pivots), f"{path.name}: box uses missing pivot group {group}")
        boxes.append(row)
    check(offset == len(data), f"{path.name}: unexpected trailing deck bytes")
    bounds = tuple((min(row[i] for row in boxes), max(row[i + 3] for row in boxes)) for i in range(1, 4))
    return {"resolution": res, "groups": pivots, "boxes": count, "bounds": bounds, "bytes": len(data)}


def validate_resources() -> None:
    required = [
        ASSETS / "textures/entity/mark_i/paint.png", ASSETS / "textures/entity/gewehr98/beech.png",
        ASSETS / "textures/item/mark_i_vehicle.png", ASSETS / "textures/item/gewehr98.png", ASSETS / "textures/item/shells_57.png",
        ASSETS / "models/item/mark_i_vehicle.json", ASSETS / "models/item/gewehr98.json", ASSETS / "models/item/shells_57.json",
        DATA / "recipes/mark_i_vehicle.json", DATA / "recipes/gewehr98.json", DATA / "recipes/shells_57.json",
        ASSETS / "deck/mark_i.deck",
    ]
    for path in required:
        check(path.is_file() and path.stat().st_size > 0, f"missing or empty resource: {path.relative_to(ROOT)}")
    for path in ASSETS.rglob("*.json"):
        json.loads(path.read_text(encoding="utf-8"))
    for path in DATA.rglob("*.json"):
        json.loads(path.read_text(encoding="utf-8"))
    for path in [ASSETS / "textures/entity/mark_i/paint.png", ASSETS / "textures/entity/gewehr98/beech.png",
                 ASSETS / "textures/item/mark_i_vehicle.png", ASSETS / "textures/item/gewehr98.png", ASSETS / "textures/item/shells_57.png"]:
        w, h = png_size_and_crc(path.read_bytes(), str(path.relative_to(ROOT)))
        check(w >= 16 and h >= 16, f"{path.name}: texture dimensions too small")
    recipes = {
        "gewehr98": "aiarsenal:gewehr98",
        "mark_i_vehicle": "aiarsenal:mark_i_vehicle",
        "shells_57": "aiarsenal:shells_57",
    }
    for name, result in recipes.items():
        recipe = json.loads((DATA / "recipes" / f"{name}.json").read_text(encoding="utf-8"))
        check(recipe.get("result", {}).get("item") == result, f"{name}: recipe output mismatch")
        check(recipe.get("type") == "minecraft:crafting_shaped", f"{name}: expected shaped crafting recipe")
    for locale, required_keys in {
        "en_us": {"item.aiarsenal.gewehr98", "item.aiarsenal.mark_i_vehicle", "item.aiarsenal.shells_57", "itemGroup.aiarsenal.wwi_vehicles"},
        "ru_ru": {"item.aiarsenal.gewehr98", "item.aiarsenal.mark_i_vehicle", "item.aiarsenal.shells_57", "itemGroup.aiarsenal.wwi_vehicles"},
    }.items():
        strings = json.loads((ASSETS / "lang" / f"{locale}.json").read_text(encoding="utf-8"))
        check(required_keys <= strings.keys(), f"{locale}: missing WWI translation keys {sorted(required_keys - strings.keys())}")
    source_checks = {
        "mods/aiarsenal/src/main/java/ru/aiforge/realwar/registry/ModEntities.java": "MARK_I",
        "mods/aiarsenal/src/main/java/ru/aiforge/realwar/registry/ModItems.java": "GEWEHR98",
        "mods/aiarsenal/src/main/java/ru/aiforge/realwar/vehicle/GunVehicle.java": "case MARK_I",
        "mods/aiarsenal/src/main/java/ru/aiforge/realwar/handheld/GunKind.java": "GEWEHR98(",
        "mods/aiarsenal/src/main/java/ru/aiforge/realwar/gametest/WWITests.java": "mark_i_sponsons_fire_as_one_salvo_in_both_modes",
        "mods/aiarsenal/src/main/java/ru/aiforge/realwar/gametest/SmallArmsTests.java": "gewehr98_round_hits_hard",
        "mods/aiarsenal/src/main/java/ru/aiforge/realwar/gametest/PenetrationTests.java": "mark_i_armour_and_track_layers",
    }
    for relative, token in source_checks.items():
        check(token in (ROOT / relative).read_text(encoding="utf-8"), f"source missing WWI integration token {token}: {relative}")


def regenerate_and_compare() -> None:
    outputs = [MODELS / "mark_i.glb", MODELS / "mark_i_lod1.glb", MODELS / "gewehr98.glb",
               ASSETS / "textures/entity/mark_i/paint.png", ASSETS / "textures/entity/gewehr98/beech.png",
               ASSETS / "textures/item/mark_i_vehicle.png", ASSETS / "textures/item/gewehr98.png",
               ASSETS / "textures/item/shells_57.png", ASSETS / "deck/mark_i.deck"]
    before = {path: sha(path) for path in outputs}
    for script in (ROOT / "tools/wwi/build_mark_i.py", ROOT / "tools/wwi/build_gewehr98.py"):
        subprocess.run([sys.executable, str(script)], cwd=ROOT, check=True)
    subprocess.run([sys.executable, str(ROOT / "tools/deck/gen_boxes.py"), "mark_i"], cwd=ROOT, check=True)
    changed = [str(path.relative_to(ROOT)) for path in outputs if sha(path) != before[path]]
    check(not changed, "asset pipeline is not byte-reproducible: " + ", ".join(changed))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rebuild", action="store_true", help="regenerate GLBs, textures, and Mark I deck; require byte-identical outputs")
    args = parser.parse_args()
    try:
        validate_resources()
        mark_i = validate_glb(MODELS / "mark_i.glb",
                              {"track_L", "track_R"},
                              {"hull", "launcher_yaw", "launcher_yaw_left", "launcher_pitch", "launcher_pitch_left",
                               "barrel", "barrel_left", "MarkI_link_L_00", "MarkI_link_R_00"})
        mark_i_gear = validate_mark_i_running_gear(parse_glb(MODELS / "mark_i.glb")[0])
        lod = validate_glb(MODELS / "mark_i_lod1.glb", {"track_L", "track_R"}, {"hull", "launcher_yaw", "launcher_yaw_left"})
        gewehr = validate_glb(MODELS / "gewehr98.glb", {"gewehr98_reload", "gewehr98_bolt"},
                              {"gewehr98.body", "gewehr98.bolt", "gewehr98.clip", "gewehr98.round", "gewehr98.sight"})
        deck = validate_deck(ASSETS / "deck/mark_i.deck")
        for model_name, texture_name in (("mark_i.glb", "mark_i/paint.png"),
                                         ("mark_i_lod1.glb", "mark_i/paint.png"),
                                         ("gewehr98.glb", "gewehr98/beech.png")):
            js, binary = parse_glb(MODELS / model_name)
            check(len(js.get("images", [])) >= 2, f"{model_name}: expected separate wood/paint and steel textures")
            view = js["bufferViews"][js["images"][0]["bufferView"]]
            start = view.get("byteOffset", 0)
            embedded = binary[start:start + view["byteLength"]]
            external = (ASSETS / "textures/entity" / texture_name).read_bytes()
            check(embedded == external, f"{model_name}: embedded atlas differs from reproducible PNG source")
        check(lod["triangles"] < mark_i["triangles"], "Mark I LOD1 must reduce triangle count")
        check(mark_i["triangles"] > 1000 and gewehr["triangles"] > 100, "unexpectedly sparse WWI geometry")
        check(1.15 < gewehr["bounds"][1][2] - gewehr["bounds"][0][2] < 1.35,
              "Gewehr 98 model length is outside the historical rifle scale")
        check(deck["boxes"] > 0 and deck["resolution"] <= 0.2001, "Mark I deck collision is missing or too coarse")
        xbounds, ybounds, zbounds = deck["bounds"]
        check(3.5 < xbounds[1] - xbounds[0] < 4.0 and 6.9 < zbounds[1] - zbounds[0] < 7.5,
              "Mark I collision footprint disagrees with the tank dimensions")
        check(0.0 <= ybounds[0] < 0.05 and 2.1 < ybounds[1] < 2.5,
              "Mark I collision height disagrees with the GLB shell")
        for spaag in ("wirbelwind", "zsu37", "gepard", "shilka"):
            sm = validate_glb(MODELS / f"{spaag}.glb", {"track_L", "track_R"},
                              {"hull", "launcher_yaw", "launcher_pitch", "barrel", "radar_dish", "sam_l", "sam_r",
                               "rw_L_0", "rw_R_0", "spk_L", "spk_R", "idl_L", "idl_R"})
            sl = validate_glb(MODELS / f"{spaag}_lod1.glb", {"track_L", "track_R"},
                              {"hull", "launcher_yaw", "launcher_pitch", "barrel", "radar_dish", "sam_l", "sam_r"})
            sd = validate_deck(ASSETS / f"deck/{spaag}.deck")
            check(9000 < sm["triangles"] < 32000, f"{spaag}: triangles {sm['triangles']} out of [9000..32000]")
            check(sl["triangles"] < sm["triangles"] * 0.6, f"{spaag}: lod1 triangles {sl['triangles']} >= 60% of {sm['triangles']}")
            check(sd["boxes"] >= 20, f"{spaag}: deck has too few boxes ({sd['boxes']})")
            png_size_and_crc((ASSETS / f"textures/item/{spaag}_vehicle.png").read_bytes(), f"{spaag} icon")
        if args.rebuild:
            regenerate_and_compare()
            print("Rebuild: byte-identical GLB, texture, and deck outputs")
        for label, result in (("Mark I", mark_i), ("Mark I LOD1", lod), ("Gewehr 98", gewehr)):
            lo, hi = result["bounds"]
            dims = tuple(hi[i] - lo[i] for i in range(3))
            print(f"{label}: {result['triangles']:,} triangles, {result['nodes']} nodes, {result['meshes']} meshes, "
                  f"{result['animations']} animations, bounds {tuple(round(v, 3) for v in dims)} m, {result['bytes']:,} bytes")
        rr = mark_i_gear["radii"]
        print(f"Mark I running gear: road={rr['road_wheel']:.3f} m at y={mark_i_gear['road_center_y']:.3f}, "
              f"sprocket/idler={rr['end_wheel']:.3f} m, return={rr['return_roller']:.3f} m "
              f"at y={mark_i_gear['roller_center_y']:.3f}, pitch={mark_i_gear['pitch']:.9f} m, "
              f"wheels={mark_i_gear['road_count']}+{mark_i_gear['roller_count']} per side; sponson yaw OK")
        print(f"Mark I collision: {deck['boxes']} boxes at {deck['resolution']:.2f} m, bounds {deck['bounds']}, {deck['bytes']:,} bytes")
        print("WWI resources: JSON/recipes/locales/PNG/GLB/animation/collision integrity OK")
        return 0
    except (InvalidAsset, OSError, KeyError, IndexError, ValueError, struct.error, json.JSONDecodeError, subprocess.CalledProcessError) as exc:
        print(f"WWI asset verification FAILED: {exc}", file=sys.stderr)
        return 1

if __name__ == "__main__":
    raise SystemExit(main())
